// Exercise #1: Decrease the Student Scores
//
// โจทย์
// - สมมุติว่าเรามี Variable ดังต้น studentScores ซึ่งบรรจุข้อมูลของคะแนนสอบของนักเรียนห้องหนึ่ง ดังนี้ [89, 70, 60, 50, 100, 71]
// - วันหนึ่งครูได้ออกมาประกาศว่า ครูตรวจข้อสอบผิดไป 1 ข้อ
//   - โดยเป็นข้อที่ทุกคนทำผิดหมดทุกคนเลย แต่ครูดันให้เป็นถูก ซึ่งข้อนี้มีคะแนน 10 คะแนน
//   - ดังนั้นครูจะหักคะแนนของทุกคนในชั้นเรียนนี้ออกมากทั้งหมด 10 คะแนน จากคะแนนที่ได้ทั้งหมด
// - ให้เขียนโปรแกรมในการหักคะแนนของนักเรียนชั้นนี้ออกมาคนละ 10 คะแนน
// - เมื่อโปรแกรมทำงานสำเร็จ ควรจะแสดงผลลัพธ์ทางหน้าจอแบบนี้
//   [79, 60, 50, 40, 90, 61]
//
// หมายเหตุ: ในไฟล์นี้ตัวแปรชื่อ scores ตามเทมเพลตของแบบฝึกหัด (โจทย์เรียกว่า studentScores)

let scores = [89, 70, 60, 50, 100, 71];

// Start coding here
// ครูตรวจข้อสอบผิด ทำให้ทุกคนได้คะแนนเกินมาคนละ 10 คะแนน
// ใช้ for loop เดินทีละตำแหน่งใน array แล้วหักคะแนนออก 10 คะแนน
for (let i = 0; i < scores.length; i++) {
  // i คือตำแหน่งใน array เริ่มที่ 0 แล้วเพิ่มทีละ 1 จนครบทุกคน
  // scores[i] คือคะแนนของนักเรียนคนนั้น
  scores[i] = scores[i] - 10;
}

console.log(scores);